/**
 * SENTINEL AI - Top Tactical Command Bar
 * Requirements:
 * - SENTINEL AI wordmark
 * - System status (Excellent/Good/Fair/Poor)
 * - Live clock
 * - Environment selector (Prod/Staging/Dev)
 * - Region selector
 * - Active incident count
 * - Collector link status
 * - Live-telemetry heartbeat indicator
 * - Labeled as SIMULATED telemetry
 */

class SentinelTopBar {
  constructor(container, store, tableEngine, audioEngine) {
    this.container = container;
    this.store = store;
    this.tableEngine = tableEngine;
    this.audioEngine = audioEngine;
    this.pulsePhase = 0;

    this.render();
    this.startClock();
    this.startPulseCanvas();
    this.bindStoreUpdates();
  }

  render() {
    this.container.innerHTML = `
      <div class="topbar-inner">
        <!-- Left: Brand & Status -->
        <div class="topbar-left">
          <div class="brand-group">
            <div class="brand-logo">
              <svg width="22" height="22" viewBox="0 0 24 24" fill="none">
                <polygon points="12,2 22,8.5 22,15.5 12,22 2,15.5 2,8.5" stroke="#00f3ff" stroke-width="2" fill="rgba(0, 243, 255, 0.1)"/>
                <circle cx="12" cy="12" r="3.5" fill="#00f3ff" />
              </svg>
            </div>
            <div class="brand-text">
              <span class="brand-title">SENTINEL<span class="text-cyan">.AI</span></span>
              <span class="simulated-pill" title="Telemetry generated by seeded simulation engine">SIMULATED STREAM</span>
            </div>
          </div>

          <div class="divider-v"></div>

          <!-- Global Status -->
          <div class="status-indicator" id="top-status-indicator">
            <span class="pulse-dot green" id="top-status-dot"></span>
            <span class="status-text text-cyan" id="top-status-label">SYS_STATE: EXCELLENT (99.98% SLA)</span>
          </div>

          <div class="divider-v"></div>

          <!-- Collector Link Status -->
          <div class="privacy-badge" title="Local Differential Privacy & Zero-Knowledge Enclave Active">
            <span class="privacy-icon">🛡️</span>
            <span class="privacy-text" id="top-collector-status">
              <span class="text-emerald">LOCAL COLLECTOR:</span> 100% PRIVATE (eBPF ACTIVE)
            </span>
          </div>
        </div>

        <!-- Center: Live Telemetry Pulse & Incident Alert Pill -->
        <div class="topbar-center">
          <div class="telemetry-stream-pill">
            <canvas id="top-pulse-canvas" width="55" height="18"></canvas>
            <span class="stream-rate">142.8k/s</span>
          </div>

          <div class="incident-alert-pill" id="top-incident-pill" style="display: none;">
            <span class="alert-icon">⚠️</span>
            <span class="alert-text" id="top-incident-title">1 CRITICAL INCIDENT</span>
          </div>
        </div>

        <!-- Right: Environment, Region, Clock, Controls -->
        <div class="topbar-right">
          <!-- Environment Picker -->
          <div class="tactical-select-wrapper">
            <span class="select-label">ENV:</span>
            <select id="env-selector" class="tactical-select">
              <option value="prod" selected>PRODUCTION</option>
              <option value="staging">STAGING</option>
              <option value="dev">LOCAL_DEV</option>
            </select>
          </div>

          <!-- Region Picker -->
          <div class="tactical-select-wrapper">
            <span class="select-label">REGION:</span>
            <select id="region-selector" class="tactical-select">
              <option value="all" selected>ALL CONTINENT</option>
              <option value="reg-north">Aethelgard (North)</option>
              <option value="reg-west">Vanguard Plains (West)</option>
              <option value="reg-center">Obsidian Basin (Center)</option>
              <option value="reg-south">Citadel Reach (South)</option>
              <option value="reg-east">Kryos Ridge (East)</option>
            </select>
          </div>

          <div class="divider-v"></div>

          <!-- Tactical Clock -->
          <div class="clock-display" id="tactical-clock">
            <span class="clock-utc" id="clock-utc">00:00:00 UTC</span>
          </div>

          <!-- Audio & Camera Controls -->
          <button class="tactical-btn icon-btn" id="btn-reset-overview" title="Reset Camera [Space]">
            <svg width="14" height="14" viewBox="0 0 24 24" fill="none" stroke="currentColor" stroke-width="2">
              <circle cx="12" cy="12" r="10"/>
              <circle cx="12" cy="12" r="3"/>
            </svg>
          </button>

          <button class="tactical-btn icon-btn" id="btn-audio-toggle" title="Toggle Sound [M]">
            <span id="audio-icon">🔊</span>
          </button>
        </div>
      </div>
    `;

    this.bindEvents();
  }

  bindEvents() {
    // Reset Camera
    const resetBtn = document.getElementById('btn-reset-overview');
    if (resetBtn) {
      resetBtn.addEventListener('click', () => {
        this.tableEngine.flyTo(560, 450, 1.0);
        this.store.selectEntity(null);
        if (this.audioEngine) this.audioEngine.playHover();
      });
    }

    // Audio Toggle
    const audioBtn = document.getElementById('btn-audio-toggle');
    if (audioBtn) {
      audioBtn.addEventListener('click', () => {
        const enabled = this.audioEngine.toggleMute();
        document.getElementById('audio-icon').textContent = enabled ? '🔊' : '🔇';
      });
    }

    // Region Selector dropdown
    const regSelect = document.getElementById('region-selector');
    if (regSelect) {
      regSelect.addEventListener('change', (e) => {
        const regId = e.target.value;
        if (regId === 'all') {
          this.tableEngine.flyTo(560, 450, 1.0);
          this.store.selectEntity(null);
        } else {
          const reg = this.store.regionsMap.get(regId);
          if (reg) {
            this.tableEngine.flyTo(reg.cx, reg.cy, 2.2);
            this.store.selectEntity(reg, 'region');
          }
        }
      });
    }

    // Incident Pill Click
    const incPill = document.getElementById('top-incident-pill');
    if (incPill) {
      incPill.addEventListener('click', () => {
        if (window.sentinelApp && window.sentinelApp.incidentModal) {
          window.sentinelApp.incidentModal.show(this.store.activeIncident);
        }
      });
    }
  }

  startClock() {
    const clockEl = document.getElementById('clock-utc');
    setInterval(() => {
      if (!clockEl) return;
      const now = new Date();
      const h = String(now.getUTCHours()).padStart(2, '0');
      const m = String(now.getUTCMinutes()).padStart(2, '0');
      const s = String(now.getUTCSeconds()).padStart(2, '0');
      clockEl.innerHTML = `${h}<span class="blink">:</span>${m}<span class="blink">:</span>${s} <span class="utc-tag">UTC</span>`;
    }, 1000);
  }

  startPulseCanvas() {
    const canvas = document.getElementById('top-pulse-canvas');
    if (!canvas) return;
    const ctx = canvas.getContext('2d');
    const w = canvas.width;
    const h = canvas.height;

    const loop = () => {
      this.pulsePhase += 0.08;
      ctx.clearRect(0, 0, w, h);

      ctx.strokeStyle = '#00f3ff';
      ctx.lineWidth = 1.5;
      ctx.beginPath();
      for (let x = 0; x < w; x++) {
        const norm = (x + this.pulsePhase * 8) % w;
        let y = h / 2;
        if (norm > 18 && norm < 23) y = h / 2 - 5;
        else if (norm >= 23 && norm < 28) y = h / 2 + 5;
        else if (norm >= 28 && norm < 32) y = h / 2 - 2;
        else y += Math.sin(norm * 0.3) * 1.2;

        if (x === 0) ctx.moveTo(x, y);
        else ctx.lineTo(x, y);
      }
      ctx.stroke();

      requestAnimationFrame(loop);
    };
    requestAnimationFrame(loop);
  }

  bindStoreUpdates() {
    this.store.subscribe((state) => {
      const statusLabel = document.getElementById('top-status-label');
      const statusDot = document.getElementById('top-status-dot');
      const incPill = document.getElementById('top-incident-pill');
      const incTitle = document.getElementById('top-incident-title');
      const collectorStatus = document.getElementById('top-collector-status');

      if (!statusLabel) return;

      const isCritical = state.globalMetrics.activeIncidents > 0;
      if (isCritical && state.activeIncident) {
        statusLabel.textContent = `SYS_STATE: POOR (INCIDENT ACTIVE)`;
        statusLabel.className = 'status-text text-red';
        statusDot.className = 'pulse-dot red';
        incPill.style.display = 'flex';
        incTitle.textContent = `${state.activeIncident.id}: ${state.activeIncident.title.toUpperCase()}`;
      } else {
        statusLabel.textContent = `SYS_STATE: EXCELLENT (99.98% SLA)`;
        statusLabel.className = 'status-text text-cyan';
        statusDot.className = 'pulse-dot green';
        incPill.style.display = 'none';
      }

      if (collectorStatus) {
        collectorStatus.innerHTML = `<span class="text-emerald">LOCAL COLLECTOR:</span> ${state.globalMetrics.collectorStatus}`;
      }
    });
  }
}

window.SentinelTopBar = SentinelTopBar;
