"""Platform admin CLI (uses the OWNER connection; never exposed over HTTP).

  uv run python -m saas_api.admin create-tenant --slug acme --name "Acme Corp" --region ap-south
  uv run python -m saas_api.admin create-user --tenant acme --email ops@acme.example \
        --role tenant_operator
  uv run python -m saas_api.admin register-collector --tenant acme --collector-id col_acme_01 \
        --write-env apps/collector/.env
  uv run python -m saas_api.admin revoke-collector --collector-id col_acme_01
  uv run python -m saas_api.admin seed-demo [--collector-env apps/collector/.env]

Secrets handling: passwords are read with a hidden prompt (or generated by seed-demo into a
git-ignored *.local file); collector tokens are written to an env file when --write-env is used,
and are otherwise printed exactly once. Only SHA-256 token hashes are stored.
"""

from __future__ import annotations

import argparse
import getpass
import re
import secrets
import sys
import uuid
from dataclasses import dataclass
from pathlib import Path

from sqlalchemy import insert, select, update

from . import audit
from .auth.collector import hash_token, new_token
from .auth.operator import ROLES, hash_password
from .config import APP_DIR, REGIONS
from .db import owner_connection
from .repo import collectors, tenants, users

ROOT = APP_DIR.parents[1]
SLUG = re.compile(r"^[a-z0-9-]{3,48}$")


@dataclass(frozen=True)
class TenantRef:
    id: uuid.UUID
    slug: str
    region: str


def find_tenant(slug: str) -> TenantRef | None:
    for region in REGIONS:
        with owner_connection(region) as c:
            row = c.execute(select(tenants).where(tenants.c.slug == slug)).first()
        if row:
            return TenantRef(row.id, row.slug, row.region)
    return None


def create_tenant(slug: str, name: str, region: str) -> TenantRef:
    if region not in REGIONS or not SLUG.fullmatch(slug):
        raise SystemExit("invalid region or slug")
    if find_tenant(slug):
        raise SystemExit(f"tenant {slug} already exists")
    tid = uuid.uuid4()
    with owner_connection(region) as c:
        c.execute(insert(tenants).values(id=tid, slug=slug, name=name, region=region))
        audit.write(c, tid, "platform_admin", "tenant_created", slug, {"region": region})
    return TenantRef(tid, slug, region)


def create_user(tenant: TenantRef, email: str, role: str, password: str) -> uuid.UUID:
    email = email.lower()
    if role not in ROLES:
        raise SystemExit(f"role must be one of {ROLES}")
    for region in REGIONS:  # emails are globally unique across regions (login searches all)
        with owner_connection(region) as c:
            if c.execute(select(users.c.id).where(users.c.email == email)).first():
                raise SystemExit("email already registered")
    uid = uuid.uuid4()
    with owner_connection(tenant.region) as c:
        c.execute(
            insert(users).values(
                id=uid, tenant_id=tenant.id, email=email, pw_hash=hash_password(password), role=role
            )
        )
        audit.write(c, tenant.id, "platform_admin", "user_created", f"user:{uid}", {"role": role})
    return uid


def register_collector(tenant: TenantRef, collector_id: str) -> str:
    token = new_token()
    with owner_connection(tenant.region) as c:
        c.execute(
            insert(collectors).values(
                id=collector_id,
                tenant_id=tenant.id,
                region=tenant.region,
                token_hash=hash_token(token),
                status="active",
            )
        )
        audit.write(c, tenant.id, "platform_admin", "collector_registered", collector_id)
    return token


def rotate_collector_token(collector_id: str) -> tuple[str, TenantRef]:
    for region in REGIONS:
        with owner_connection(region) as c:
            row = c.execute(select(collectors).where(collectors.c.id == collector_id)).first()
            if row:
                token = new_token()
                c.execute(
                    update(collectors)
                    .where(collectors.c.id == collector_id)
                    .values(token_hash=hash_token(token), status="active")
                )
                audit.write(
                    c, row.tenant_id, "platform_admin", "collector_token_rotated", collector_id
                )
                t = c.execute(select(tenants).where(tenants.c.id == row.tenant_id)).first()
                return token, TenantRef(t.id, t.slug, t.region)
    raise SystemExit("collector not found")


def revoke_collector(collector_id: str) -> None:
    for region in REGIONS:
        with owner_connection(region) as c:
            row = c.execute(select(collectors).where(collectors.c.id == collector_id)).first()
            if row:
                c.execute(
                    update(collectors)
                    .where(collectors.c.id == collector_id)
                    .values(status="revoked")
                )
                audit.write(c, row.tenant_id, "platform_admin", "collector_revoked", collector_id)
                return
    raise SystemExit("collector not found")


def write_env(path: Path, values: dict[str, str]) -> None:
    """Set keys in a .env file (replace or append) without printing values."""
    lines = path.read_text(encoding="utf-8").splitlines() if path.exists() else []
    keys_done: set[str] = set()
    out = []
    for line in lines:
        k = line.split("=", 1)[0]
        if k in values:
            out.append(f"{k}={values[k]}")
            keys_done.add(k)
        else:
            out.append(line)
    out += [f"{k}={v}" for k, v in values.items() if k not in keys_done]
    path.write_text("\n".join(out) + "\n", encoding="utf-8", newline="\n")


DEMO = (
    # slug, name, region, collector_id, [(email, role)]
    (
        "acme",
        "Acme Corp (demo)",
        "ap-south",
        "col_acme_01",
        [("ops@acme.example", "tenant_operator"), ("admin@acme.example", "tenant_admin")],
    ),
    (
        "initech",
        "Initech (demo)",
        "ap-south",
        "col_initech_01",
        [("ops@initech.example", "tenant_operator")],
    ),
    (
        "globex",
        "Globex GmbH (demo)",
        "eu-west",
        "col_globex_01",
        [("ops@globex.example", "tenant_operator")],
    ),
)


CREDS_FILE = APP_DIR / ".demo-operators.local"


def _show(p: Path) -> str:
    p = p.resolve()
    return str(p.relative_to(ROOT)) if p.is_relative_to(ROOT) else str(p)


def save_credential(slug: str, role: str, email: str, pw: str) -> None:
    """Persist a generated password IMMEDIATELY (git-ignored file) - never only in memory."""
    new = not CREDS_FILE.exists()
    with CREDS_FILE.open("a", encoding="utf-8") as fh:
        if new:
            fh.write("# AEGIS demo operator credentials (git-ignored, local only)\n")
        fh.write(f"{slug}\t{role}\t{email}\t{pw}\n")


def reset_password(email: str, pw: str) -> tuple[TenantRef, str]:
    email = email.lower()
    for region in REGIONS:
        with owner_connection(region) as c:
            row = c.execute(select(users).where(users.c.email == email)).first()
            if row:
                c.execute(
                    update(users).where(users.c.id == row.id).values(pw_hash=hash_password(pw))
                )
                audit.write(c, row.tenant_id, "platform_admin", "password_reset", f"user:{row.id}")
                t = c.execute(select(tenants).where(tenants.c.id == row.tenant_id)).first()
                return TenantRef(t.id, t.slug, t.region), row.role
    raise SystemExit("user not found")


def seed_demo(collector_env: Path | None) -> None:
    for slug, name, region, col_id, people in DEMO:
        t = find_tenant(slug)
        if t:
            print(f"exists   tenant {slug} ({t.region})")
            continue
        t = create_tenant(slug, name, region)
        print(f"created  tenant {slug} ({region})")
        for email, role in people:
            pw = secrets.token_urlsafe(18)
            save_credential(slug, role, email, pw)  # saved BEFORE the account exists
            create_user(t, email, role, pw)
            print(f"created  user {email} ({role}); password -> {_show(CREDS_FILE)} (hidden)")
        env_path = (
            collector_env.resolve()
            if (collector_env and slug == "acme")
            else ROOT / "apps" / "collector" / f".env.{slug}"
        )
        token = register_collector(t, col_id)
        write_env(
            env_path,
            {
                "AEGIS_COL_COLLECTOR_ID": col_id,
                "AEGIS_COL_REGION": region,
                "AEGIS_COL_COLLECTOR_TOKEN": token,
            },
        )
        print(f"created  collector {col_id}; token -> {_show(env_path)} (hidden)")


def main(argv: list[str] | None = None) -> None:
    ap = argparse.ArgumentParser(prog="saas_api.admin")
    sub = ap.add_subparsers(dest="cmd", required=True)
    p = sub.add_parser("create-tenant")
    p.add_argument("--slug", required=True)
    p.add_argument("--name", required=True)
    p.add_argument("--region", required=True, choices=REGIONS)
    p = sub.add_parser("create-user")
    p.add_argument("--tenant", required=True)
    p.add_argument("--email", required=True)
    p.add_argument("--role", required=True, choices=ROLES)
    p = sub.add_parser("register-collector")
    p.add_argument("--tenant", required=True)
    p.add_argument("--collector-id", required=True)
    p.add_argument("--write-env", type=Path)
    p = sub.add_parser("rotate-collector-token")
    p.add_argument("--collector-id", required=True)
    p.add_argument("--write-env", type=Path)
    p = sub.add_parser("revoke-collector")
    p.add_argument("--collector-id", required=True)
    p = sub.add_parser("reset-password")
    p.add_argument("--email", required=True)
    p.add_argument(
        "--generate",
        action="store_true",
        help="generate a password and save it to the git-ignored .demo-operators.local",
    )
    p = sub.add_parser("seed-demo")
    p.add_argument("--collector-env", type=Path, help="env file for the acme collector")
    a = ap.parse_args(argv)

    if a.cmd == "create-tenant":
        t = create_tenant(a.slug, a.name, a.region)
        print(f"created tenant {t.slug} id={t.id} region={t.region}")
    elif a.cmd == "create-user":
        t = find_tenant(a.tenant) or sys.exit("tenant not found")
        pw = getpass.getpass("Password (min 12 chars, hidden): ")
        if pw != getpass.getpass("Repeat password: "):
            sys.exit("passwords do not match")
        create_user(t, a.email, a.role, pw)
        print(f"created user {a.email.lower()} ({a.role}) in {t.slug}")
    elif a.cmd in ("register-collector", "rotate-collector-token"):
        if a.cmd == "register-collector":
            t = find_tenant(a.tenant) or sys.exit("tenant not found")
            token = register_collector(t, a.collector_id)
        else:
            token, t = rotate_collector_token(a.collector_id)
        if a.write_env:
            write_env(
                a.write_env,
                {
                    "AEGIS_COL_COLLECTOR_ID": a.collector_id,
                    "AEGIS_COL_REGION": t.region,
                    "AEGIS_COL_COLLECTOR_TOKEN": token,
                },
            )
            print(f"token written to {a.write_env} (value hidden)")
        else:
            print("Collector token (shown ONCE, store it in the collector's .env):")
            print(token)
    elif a.cmd == "revoke-collector":
        revoke_collector(a.collector_id)
        print(f"revoked {a.collector_id}")
    elif a.cmd == "reset-password":
        if a.generate:
            pw = secrets.token_urlsafe(18)
            t, role = reset_password(a.email, pw)
            save_credential(t.slug, role, a.email.lower(), pw)
            print(f"password reset for {a.email.lower()}; saved to {_show(CREDS_FILE)} (hidden)")
        else:
            pw = getpass.getpass("New password (min 12 chars, hidden): ")
            if pw != getpass.getpass("Repeat password: "):
                sys.exit("passwords do not match")
            reset_password(a.email, pw)
            print(f"password reset for {a.email.lower()}")
    elif a.cmd == "seed-demo":
        seed_demo(a.collector_env)


if __name__ == "__main__":
    main()
